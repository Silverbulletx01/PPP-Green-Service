let currentLang = localStorage.getItem('ppp-lang') || 'th';

function t(key) {
  return translations[currentLang]?.[key] || translations['en']?.[key] || key;
}

function applyTranslations() {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    el.textContent = t(key);
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    el.placeholder = t(key);
  });
  document.documentElement.lang = currentLang === 'th' ? 'th' : 'en';
}

function toggleLanguage() {
  currentLang = currentLang === 'th' ? 'en' : 'th';
  localStorage.setItem('ppp-lang', currentLang);
  applyTranslations();
  // Re-render all dynamic content for language consistency
  if (typeof refreshCharts === 'function') refreshCharts();
  if (typeof renderRecentActivity === 'function') renderRecentActivity();
  if (typeof renderRecords === 'function') renderRecords();
  if (typeof renderGallery === 'function') renderGallery();
  if (typeof updateSettingsPage === 'function') updateSettingsPage();
  if (typeof updatePageSubtitle === 'function') updatePageSubtitle();
  if (typeof refreshOpenRecordDetailLanguage === 'function') refreshOpenRecordDetailLanguage();
}

// Apply on load
document.addEventListener('DOMContentLoaded', () => {
  applyTranslations();
});
